"""Regenerates models.js from Catalyst Edit's own model definitions.

Run this again after updating Catalyst Edit:
    python make_models.py
"""
import json
import os
import sys

CATALYST_RES = r"C:\Program Files (x86)\Line6\Catalyst Edit\res"
HERE = os.path.dirname(os.path.abspath(__file__))

GROUPS = {
    "amps": ["amps.models"],
    "effects": ["Delays.models", "Modulations.models", "Pitch.models"],
    "reverbs": ["reverbs.models"],
    "fixed": ["fixed.models"],
}
EFFECT_KIND = {"Delays.models": "delay", "Modulations.models": "mod", "Pitch.models": "pitch"}


def load(name):
    with open(os.path.join(CATALYST_RES, name), encoding="utf-8") as f:
        return json.load(f)


def main():
    out = {}
    for group, files in GROUPS.items():
        out[group] = {}
        for fname in files:
            for model in load(fname):
                params = {}
                for p in model.get("params", []):
                    params[p["symbolicID"]] = {
                        "label": p.get("name", p["symbolicID"]),
                        "min": p["min"],
                        "max": p["max"],
                        "default": p["default"],
                    }
                out[group][model["symbolicID"]] = {
                    "name": model.get("name", model["symbolicID"]).strip(" '"),
                    "kind": EFFECT_KIND.get(fname),
                    "params": params,
                }
    js = "// Generated by make_models.py from Catalyst Edit's res folder. Do not edit by hand.\n"
    js += "window.CATALYST_MODELS = " + json.dumps(out, indent=1) + ";\n"
    with open(os.path.join(HERE, "models.js"), "w", encoding="utf-8") as f:
        f.write(js)
    counts = {k: len(v) for k, v in out.items()}
    print("Wrote models.js", counts)


if __name__ == "__main__":
    sys.exit(main())
